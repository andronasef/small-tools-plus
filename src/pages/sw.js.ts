import type { APIRoute } from 'astro';
import fs from 'node:fs';
import path from 'node:path';
import { tools } from '../data/tools';

export const prerender = true;

export const GET: APIRoute = async () => {
  const localFiles = [
    './',
    './index.html',
    './manifest.webmanifest',
    './icons/icon.svg',
    './icons/icon-192.png',
    './icons/icon-512.png',
    './icons/icon-maskable-512.png',
    './style.css',
    './tailwind.css'
  ];

  for (const tool of tools) {
    localFiles.push(`./${tool.file}`);
    localFiles.push(`./icons/${tool.iconFile}`);
    if (tool.mobile) {
      const manifestName = tool.manifest || `manifest-${tool.id}.webmanifest`;
      const iconBase = tool.iconFile.replace('.svg', '');
      localFiles.push(`./${manifestName}`);
      localFiles.push(`./icons/${iconBase}-192.png`);
      localFiles.push(`./icons/${iconBase}-512.png`);
    }
  }

  const workoutDir = path.resolve('public/workout-media');
  if (fs.existsSync(workoutDir)) {
    const files = fs.readdirSync(workoutDir);
    for (const f of files) {
      if (!f.startsWith('.')) {
        localFiles.push(`./workout-media/${f}`);
      }
    }
  }

  const remoteAssets = [
    'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/css/all.min.css',
    'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/webfonts/fa-solid-900.woff2',
    'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/webfonts/fa-regular-400.woff2',
    'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/webfonts/fa-brands-400.woff2',
    'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500;600&display=swap',
    'https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700;800&family=JetBrains+Mono:wght@500;700&display=swap',
    'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@300;400;500;600;700&display=swap',
    'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@400;500;600;700&display=swap',
    'https://fonts.googleapis.com/css2?family=Reem+Kufi:wght@400;600&family=IBM+Plex+Sans+Arabic:wght@300;400;500&display=swap'
  ];

  const precacheList = Array.from(new Set([...localFiles, ...remoteAssets]));
  const cacheName = `small-tools-plus-v${Date.now().toString(36)}`;

  const swScript = `/*
  Small Tools Plus — Service Worker (Auto-generated by Astro SSG)
  Cache Version: ${cacheName}
*/

const CACHE_NAME = '${cacheName}';
const PRECACHE_MANIFEST = ${JSON.stringify(precacheList, null, 2)};

self.addEventListener('install', (event) => {
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE_NAME).then(async (cache) => {
      for (const url of PRECACHE_MANIFEST) {
        try {
          const req = new Request(url, {
            mode: url.startsWith('http') && !url.includes(self.location.hostname) ? 'no-cors' : 'cors'
          });
          const res = await fetch(req);
          if (res) {
            await cache.put(url, res);
          }
        } catch (err) {
          console.warn('[SW] Precache skip:', url, err);
        }
      }
    })
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    Promise.all([
      self.clients.claim(),
      caches.keys().then((keys) => {
        return Promise.all(
          keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
        );
      })
    ])
  );
});

async function handleRangeRequest(request) {
  const rangeHeader = request.headers.get('range');
  const cache = await caches.open(CACHE_NAME);
  let cachedResponse = await cache.match(request.url);

  if (!cachedResponse) {
    try {
      return await fetch(request);
    } catch (err) {
      return new Response('Media unavailable offline', {
        status: 503,
        statusText: 'Service Unavailable',
        headers: { 'Content-Type': 'text/plain' }
      });
    }
  }

  if (!rangeHeader) {
    return cachedResponse;
  }

  const arrayBuffer = await cachedResponse.arrayBuffer();
  const totalLength = arrayBuffer.byteLength;
  const matches = rangeHeader.match(/bytes=(\\d+)-(\\d*)/);

  if (!matches) {
    return cachedResponse;
  }

  const start = parseInt(matches[1], 10);
  const end = matches[2] ? parseInt(matches[2], 10) : totalLength - 1;

  if (start >= totalLength || end >= totalLength) {
    return new Response('', {
      status: 416,
      statusText: 'Range Not Satisfiable',
      headers: { 'Content-Range': \`bytes */\${totalLength}\` }
    });
  }

  const sliced = arrayBuffer.slice(start, end + 1);
  const headers = new Headers(cachedResponse.headers);
  headers.set('Content-Range', \`bytes \${start}-\${end}/\${totalLength}\`);
  headers.set('Content-Length', String(sliced.byteLength));
  headers.set('Accept-Ranges', 'bytes');
  if (!headers.get('Content-Type')) {
    headers.set('Content-Type', request.url.endsWith('.mp4') ? 'video/mp4' : 'application/octet-stream');
  }

  return new Response(sliced, {
    status: 206,
    statusText: 'Partial Content',
    headers
  });
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  if (request.headers.get('range') || request.url.match(/\\.(mp4|webm|ogg|mp3|wav)($|\\?)/i)) {
    event.respondWith(handleRangeRequest(request));
    return;
  }

  event.respondWith(
    (async () => {
      const cached = await caches.match(request, { ignoreSearch: false });
      if (cached) return cached;

      const cleanUrl = request.url.split('?')[0];
      if (cleanUrl !== request.url) {
        const cachedClean = await caches.match(cleanUrl);
        if (cachedClean) return cachedClean;
      }

      try {
        const netResponse = await fetch(request);
        if (netResponse && (netResponse.status === 200 || netResponse.status === 0)) {
          const cache = await caches.open(CACHE_NAME);
          cache.put(request, netResponse.clone()).catch(() => {});
        }
        return netResponse;
      } catch (err) {
        if (request.mode === 'navigate') {
          const fallback = await caches.match('./index.html');
          if (fallback) return fallback;
        }
        throw err;
      }
    })()
  );
});

self.addEventListener('message', (event) => {
  const { data } = event;
  if (data && data.action === 'SKIP_WAITING') {
    self.skipWaiting();
  }
  if (data && data.action === 'CACHE_ALL_ASSETS') {
    event.waitUntil(
      (async () => {
        const client = event.source;
        const cache = await caches.open(CACHE_NAME);
        const list = Array.from(new Set([...PRECACHE_MANIFEST, ...(data.extraUrls || [])]));
        let completed = 0;
        const total = list.length;

        for (const url of list) {
          try {
            const req = new Request(url, {
              mode: url.startsWith('http') && !url.includes(self.location.hostname) ? 'no-cors' : 'cors'
            });
            const res = await fetch(req);
            if (res) {
              await cache.put(url, res);
            }
          } catch (e) {
            console.warn('[SW Download] Failed:', url, e);
          }
          completed++;
          if (client && client.postMessage) {
            client.postMessage({
              type: 'CACHE_PROGRESS',
              current: completed,
              total,
              url,
              done: completed === total
            });
          }
        }
      })()
    );
  }
});
`;

  return new Response(swScript, {
    headers: {
      'Content-Type': 'application/javascript; charset=utf-8'
    }
  });
};
